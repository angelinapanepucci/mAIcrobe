"""
Module responsible for plotting mAIcrobe morphology results.

This module expects a combined pandas DataFrame generated by the mAIcrobe
results loading workflow. It does not read CSV files directly.

The intended workflow is:

    result = experiment.load()
    df = result.data

    plot_result = plot_measurement_by_condition(
        df,
        measurement="Width",
        plot_type="violin_box",
    )

The napari GUI should use this module to:
    - discover plottable morphology columns,
    - let the user select a measurement,
    - create seaborn/matplotlib figures,
    - optionally save the figure.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal, Mapping, Sequence

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
from matplotlib.axes import Axes
from matplotlib.figure import Figure


PlotType = Literal[
    "violin_box",
    "box",
    "box_strip",
    "strip",
    "swarm",
]


DEFAULT_MORPHOLOGY_COLUMNS = [
    "Area",
    "Perimeter",
    "Eccentricity",
    "Width",
    "Length",
]

DEFAULT_METADATA_COLUMNS = [
    "condition",
    "replicate",
    "image",
    "label",
    "frame",
    "source_file",
    "source_stem",
    "source_path",
    "global_object_id",
    "Shape Analysis Status",
]


@dataclass
class MorphologyPlotConfig:
    """
    Configuration for a morphology plot.

    This dataclass is intentionally GUI-friendly: a napari widget can expose
    these values as dropdowns, checkboxes, and text fields.
    """

    measurement: str
    condition_col: str = "condition"
    hue_col: str | None = None

    plot_type: PlotType = "violin_box"

    title: str | None = None
    xlabel: str | None = None
    ylabel: str | None = None

    condition_order: Sequence[Any] | None = None
    hue_order: Sequence[Any] | None = None
    max_points_for_scatter: int | None = 5000
    sample_n: int | None = 5000
    random_state: int = 0 

    condition_labels: Mapping[Any, str] | None = None
    legend_title: str | None = None
    legend_labels: Mapping[Any, str] | None = None
    show_legend: bool = True
    legend_loc: str = "best"
    legend_bbox_to_anchor: tuple[float, float] | None = None

    show_n: bool = True
    n_label: str = "n"

    keep_failed: bool = False
    status_col: str = "Shape Analysis Status"
    computed_status: str = "computed"

    show_points: bool = True
    point_alpha: float = 0.45
    point_size: float = 3.0
    jitter: bool | float = True

    violin_inner: str | None = None
    violin_cut: float = 0
    violin_scale: Literal["area", "count", "width"] = "width"

    box_width: float = 0.18
    box_whis: tuple[float, float] | float = (5, 95)
    show_fliers: bool = False

    figsize: tuple[float, float] = (7.0, 5.0)
    dpi: int = 120

    rotate_xticks: bool = False
    xtick_rotation: float = 30
    despine: bool = True
    tight_layout: bool = True


@dataclass
class MorphologyPlotResult:
    """
    Result returned by plotting functions.

    The napari GUI can use:
        result.fig
        result.ax
        result.data
        result.counts
        result.warnings
    """

    fig: Figure
    ax: Axes
    data: pd.DataFrame
    counts: pd.DataFrame
    warnings: list[str] = field(default_factory=list)


def get_numeric_columns(
    df: pd.DataFrame,
    *,
    exclude_metadata: bool = True,
) -> list[str]:
    """
    Return numeric columns available for plotting.

    Parameters
    ----------
    df:
        Combined mAIcrobe results DataFrame.

    exclude_metadata:
        Whether to exclude known metadata columns such as label, frame,
        condition, replicate, and source_file.

    Returns
    -------
    numeric_columns:
        Numeric columns that can be offered to the user in the GUI.
    """

    numeric_columns: list[str] = []

    for col in df.columns:
        if exclude_metadata and col in DEFAULT_METADATA_COLUMNS:
            continue

        series = df[col]
        # fast path: already numeric dtype
        if pd.api.types.is_numeric_dtype(series):
            numeric_columns.append(col)
            continue
        # otherwise try a conservative inference: treat as numeric if at least
        # 90% of values can be coerced to numeric
        coerced = pd.to_numeric(series, errors="coerce")
        if coerced.notna().sum() / max(1, len(series)) >= 0.9:
            numeric_columns.append(col)

    return numeric_columns


def get_morphology_columns(
    df: pd.DataFrame,
    *,
    preferred_columns: Sequence[str] | None = None,
) -> list[str]:
    """
    Return known mAIcrobe morphology columns that are present and numeric.

    This is the best function to use for the GUI dropdown if the graphing
    interface should focus on morphology measurements only.
    """

    if preferred_columns is None:
        preferred_columns = DEFAULT_MORPHOLOGY_COLUMNS

    available: list[str] = []

    for col in preferred_columns:
        if col not in df.columns:
            continue

        numeric = pd.to_numeric(df[col], errors="coerce")

        if numeric.notna().any():
            available.append(col)

    return available


def prepare_plot_data(
    df: pd.DataFrame,
    config: MorphologyPlotConfig,
) -> tuple[pd.DataFrame, list[str]]:
    """
    Validate, clean, and subset a DataFrame before plotting.

    This function:
        - checks required columns,
        - converts the selected measurement to numeric,
        - optionally filters failed shape-analysis rows,
        - removes rows without condition or measurement values.

    Returns
    -------
    plot_data:
        Cleaned DataFrame ready for seaborn.

    warnings:
        Warnings generated during preparation.
    """

    warnings: list[str] = []
    required_columns = [config.measurement, config.condition_col]

    if config.hue_col is not None:
        required_columns.append(config.hue_col)

    missing_columns = [
        col for col in required_columns
        if col not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            "Cannot create morphology plot. Missing required columns: "
            f"{missing_columns}"
        )

    plot_data = df.copy()

    original_n_rows = len(plot_data)

    plot_data[config.measurement] = pd.to_numeric(
        plot_data[config.measurement],
        errors="coerce",
    )

    if (
        not config.keep_failed
        and config.status_col in plot_data.columns
    ):
        statuses = (
            plot_data[config.status_col]
            .astype(str)
            .str.strip()
            .str.lower()
        )

        plot_data = plot_data[
            statuses == config.computed_status.lower()
        ].copy()

        n_removed = original_n_rows - len(plot_data)

        if n_removed > 0:
            warnings.append(
                f"Removed {n_removed} rows where "
                f"{config.status_col!r} was not {config.computed_status!r}."
            )

    before_dropna = len(plot_data)

    subset_cols = [config.measurement, config.condition_col]

    if config.hue_col is not None:
        subset_cols.append(config.hue_col)

    plot_data = plot_data.dropna(subset=subset_cols).copy()

    n_dropped = before_dropna - len(plot_data)

    if n_dropped > 0:
        warnings.append(
            f"Dropped {n_dropped} rows with missing condition, hue, "
            "or measurement values."
        )

    if plot_data.empty:
        raise ValueError(
            "No rows remain after filtering. Check the selected measurement, "
            "condition column, and Shape Analysis Status filtering."
        )

    # Normalize condition/hue strings and apply categorical ordering if provided.
    plot_data[config.condition_col] = (
        plot_data[config.condition_col].astype(str).str.strip()
    )

    if config.condition_order is not None:
        # preserve user order using categorical dtype
        plot_data[config.condition_col] = pd.Categorical(
            plot_data[config.condition_col],
            categories=[str(x) for x in config.condition_order],
            ordered=True,
        )

    if config.hue_col is not None:
        plot_data[config.hue_col] = (
            plot_data[config.hue_col].astype(str).str.strip()
        )

        if config.hue_order is not None:
            plot_data[config.hue_col] = pd.Categorical(
                plot_data[config.hue_col],
                categories=[str(x) for x in config.hue_order],
                ordered=True,
            )

    # Downsample if there are too many points to plot for point-based plots with individual dots.
    point_data = plot_data

    if (
        config.plot_type in ["strip", "swarm", "box_strip", "violin_box"]
        and config.show_points
    ):
        n_rows = len(plot_data)

        if n_rows > config.max_points_for_scatter and config.sample_n is not None:
            warnings.append(
                f"Downsampling from {len(point_data)} to 5000 points for plotting."
            )
            point_data = point_data.sample(
                n=config.sample_n,
                random_state=0,
            ).reset_index(drop=True)

    return plot_data, warnings


def count_plotted_cells(
    plot_data: pd.DataFrame,
    *,
    condition_col: str = "condition",
    hue_col: str | None = None,
) -> pd.DataFrame:
    """
    Count how many cells are plotted per condition.

    If hue_col is provided, counts are calculated per condition and hue group.
    """

    if hue_col is None:
        counts = (
            plot_data
            .groupby(condition_col, dropna=False)
            .size()
            .reset_index(name="n")
        )
    else:
        counts = (
            plot_data
            .groupby([condition_col, hue_col], dropna=False)
            .size()
            .reset_index(name="n")
        )

    return counts


def _condition_order(
    plot_data: pd.DataFrame,
    config: MorphologyPlotConfig,
) -> list[str]:
    """
    Resolve condition plotting order.
    """

    if config.condition_order is not None:
        return [str(value) for value in config.condition_order]

    return sorted(plot_data[config.condition_col].dropna().unique())


def _hue_order(
    plot_data: pd.DataFrame,
    config: MorphologyPlotConfig,
) -> list[str] | None:
    """
    Resolve hue plotting order.
    """

    if config.hue_col is None:
        return None

    if config.hue_order is not None:
        return [str(value) for value in config.hue_order]

    return sorted(plot_data[config.hue_col].dropna().unique())


def _add_n_to_xtick_labels(
    ax: Axes,
    counts: pd.DataFrame,
    *,
    condition_col: str,
    order: Sequence[str],
    condition_labels: Mapping[Any, str] | None = None,
    n_label: str = "n",
) -> None:
    """
    Append plotted cell counts to x-axis tick labels.

    Example:
        WT
        n=254
    """

    count_map = {
        str(row[condition_col]): int(row["n"])
        for _, row in counts.iterrows()
    }

    labels: list[str] = []

    for condition in order:
        display_label = condition

        if condition_labels is not None:
            display_label = condition_labels.get(
                condition,
                condition_labels.get(str(condition), condition),
            )

        n = count_map.get(str(condition), 0)
        labels.append(f"{display_label}\n{n_label}={n}")

    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels)


def _apply_axis_labels(
    ax: Axes,
    config: MorphologyPlotConfig,
) -> None:
    """
    Apply title and axis labels.
    """

    if config.title is not None:
        ax.set_title(config.title)

    if config.xlabel is not None:
        ax.set_xlabel(config.xlabel)
    else:
        ax.set_xlabel(config.condition_col)

    if config.ylabel is not None:
        ax.set_ylabel(config.ylabel)
    else:
        ax.set_ylabel(config.measurement)


def _customize_legend(
    ax: Axes,
    config: MorphologyPlotConfig,
) -> None:
    """
    Customize or remove the legend.
    """

    legend = ax.get_legend()

    if legend is None:
        return

    if not config.show_legend:
        legend.remove()
        return

    handles, labels = ax.get_legend_handles_labels()

    if not handles:
        return

    new_labels = labels

    if config.legend_labels is not None:
        new_labels = [
            config.legend_labels.get(
                label,
                config.legend_labels.get(str(label), label),
            )
            for label in labels
        ]

    title = config.legend_title

    if title is None and config.hue_col is not None:
        title = config.hue_col

    ax.legend(
        handles,
        new_labels,
        title=title,
        loc=config.legend_loc,
        bbox_to_anchor=config.legend_bbox_to_anchor,
        frameon=False,
    )


def _finish_axes(
    ax: Axes,
    config: MorphologyPlotConfig,
) -> None:
    """
    Apply final visual formatting.
    """

    _apply_axis_labels(ax, config)
    _customize_legend(ax, config)

    if config.rotate_xticks:
        for label in ax.get_xticklabels():
            label.set_rotation(config.xtick_rotation)
            label.set_horizontalalignment("right")

    if config.despine:
        sns.despine(ax=ax)

    if config.tight_layout:
        ax.figure.tight_layout()


def _plot_violin_box(
    ax: Axes,
    plot_data: pd.DataFrame,
    config: MorphologyPlotConfig,
    *,
    order: Sequence[str],
    hue_order: Sequence[str] | None,
) -> None:
    """
    Plot a violin distribution with an internal box-and-whisker overlay.

    The violin shows the full distribution. The boxplot overlay shows the
    median, interquartile range, and whiskers. By default, whiskers represent
    the 5th and 95th percentiles.
    """

    sns.violinplot(
        data=plot_data,
        x=config.condition_col,
        y=config.measurement,
        hue=config.hue_col,
        order=order,
        hue_order=hue_order,
        inner=config.violin_inner,
        cut=config.violin_cut,
        scale=config.violin_scale,
        ax=ax,
    )

    sns.boxplot(
        data=plot_data,
        x=config.condition_col,
        y=config.measurement,
        hue=config.hue_col,
        order=order,
        hue_order=hue_order,
        width=config.box_width,
        whis=config.box_whis,
        showcaps=True,
        showfliers=config.show_fliers,
        boxprops={"facecolor": "white", "zorder": 3},
        whiskerprops={"zorder": 3},
        capprops={"zorder": 3},
        medianprops={"zorder": 4},
        ax=ax,
    )

    if config.show_points:
        sns.stripplot(
            data=plot_data,
            x=config.condition_col,
            y=config.measurement,
            hue=config.hue_col,
            order=order,
            hue_order=hue_order,
            dodge=config.hue_col is not None,
            jitter=config.jitter,
            alpha=config.point_alpha,
            size=config.point_size,
            ax=ax,
        )

    _remove_duplicate_legend_entries(ax)


def _remove_duplicate_legend_entries(ax: Axes) -> None:
    """
    Remove duplicate legend entries caused by overlaying multiple seaborn plots.
    """

    handles, labels = ax.get_legend_handles_labels()

    if not handles:
        return

    unique: dict[str, Any] = {}

    for handle, label in zip(handles, labels):
        if label not in unique:
            unique[label] = handle

    ax.legend(
        unique.values(),
        unique.keys(),
        frameon=False,
    )


def plot_measurement_by_condition(
    df: pd.DataFrame,
    measurement: str,
    *,
    condition_col: str = "condition",
    hue_col: str | None = None,
    plot_type: PlotType = "violin_box",
    title: str | None = None,
    xlabel: str | None = None,
    ylabel: str | None = None,
    condition_order: Sequence[Any] | None = None,
    hue_order: Sequence[Any] | None = None,
    condition_labels: Mapping[Any, str] | None = None,
    legend_title: str | None = None,
    legend_labels: Mapping[Any, str] | None = None,
    show_legend: bool = True,
    show_n: bool = True,
    keep_failed: bool = False,
    figsize: tuple[float, float] = (7.0, 5.0),
    dpi: int = 120,
) -> MorphologyPlotResult:
    """
    Plot one morphology measurement grouped by experimental condition.

    Parameters
    ----------
    df:
        Combined mAIcrobe results DataFrame.

    measurement:
        Morphological feature to plot, for example "Width", "Length", or "Area".

    condition_col:
        Column containing experimental conditions.

    hue_col:
        Optional secondary grouping column, for example "replicate".

    plot_type:
        Type of plot to create. Recommended default is "violin_box".

    title, xlabel, ylabel:
        User-customizable plot and axis titles.

    condition_order:
        Optional order for conditions along the x-axis.

    hue_order:
        Optional order for hue groups.

    condition_labels:
        Optional mapping from raw condition names to display labels.

    legend_title:
        Optional custom legend title.

    legend_labels:
        Optional mapping from raw legend labels to display labels.

    show_legend:
        Whether to show the legend.

    show_n:
        Whether to append plotted cell counts to x-axis labels.

    keep_failed:
        Whether to keep rows where Shape Analysis Status is not computed.

    figsize:
        Matplotlib figure size.

    dpi:
        Matplotlib figure resolution.

    Returns
    -------
    MorphologyPlotResult
        Object containing the figure, axes, cleaned plot data, counts, and
        warnings.
    """

    config = MorphologyPlotConfig(
        measurement=measurement,
        condition_col=condition_col,
        hue_col=hue_col,
        plot_type=plot_type,
        title=title,
        xlabel=xlabel,
        ylabel=ylabel,
        condition_order=condition_order,
        hue_order=hue_order,
        condition_labels=condition_labels,
        legend_title=legend_title,
        legend_labels=legend_labels,
        show_legend=show_legend,
        show_n=show_n,
        keep_failed=keep_failed,
        figsize=figsize,
        dpi=dpi,
    )

    return plot_from_config(df, config)


def plot_from_config(
    df: pd.DataFrame,
    config: MorphologyPlotConfig,
) -> MorphologyPlotResult:
    """
    Create a morphology plot from a MorphologyPlotConfig object.

    This function is especially useful for napari widgets, because the widget
    can build the config from GUI values and pass it here.
    """

    plot_data, warnings = prepare_plot_data(df, config)

    order = _condition_order(plot_data, config)
    hue_order = _hue_order(plot_data, config)

    if config.hue_col is None:
        counts = count_plotted_cells(
            plot_data,
            condition_col=config.condition_col,
        )
    else:
        # For axis labels, use total n per condition.
        counts = count_plotted_cells(
            plot_data,
            condition_col=config.condition_col,
        )

    fig, ax = plt.subplots(
        figsize=config.figsize,
        dpi=config.dpi,
    )

    # Use a context and try/except around plotting to capture plotting failures
    try:
        if config.plot_type == "violin_box":
            _plot_violin_box(
                ax,
                plot_data,
                config,
                order=order,
                hue_order=hue_order,
            )

        elif config.plot_type == "box":
            sns.boxplot(
                data=plot_data,
                x=config.condition_col,
                y=config.measurement,
                hue=config.hue_col,
                order=order,
                hue_order=hue_order,
                whis=config.box_whis,
                showfliers=config.show_fliers,
                ax=ax,
            )

        elif config.plot_type == "box_strip":
            sns.boxplot(
                data=plot_data,
                x=config.condition_col,
                y=config.measurement,
                hue=config.hue_col,
                order=order,
                hue_order=hue_order,
                whis=config.box_whis,
                showfliers=config.show_fliers,
                ax=ax,
            )

            if config.show_points:
                sns.stripplot(
                    data=plot_data,
                    x=config.condition_col,
                    y=config.measurement,
                    hue=config.hue_col,
                    order=order,
                    hue_order=hue_order,
                    dodge=config.hue_col is not None,
                    jitter=config.jitter,
                    alpha=config.point_alpha,
                    size=config.point_size,
                    ax=ax,
                )

            _remove_duplicate_legend_entries(ax)

        elif config.plot_type == "strip":
            sns.stripplot(
                data=plot_data,
                x=config.condition_col,
                y=config.measurement,
                hue=config.hue_col,
                order=order,
                hue_order=hue_order,
                dodge=config.hue_col is not None,
                jitter=config.jitter,
                alpha=config.point_alpha,
                size=config.point_size,
                ax=ax,
            )

        elif config.plot_type == "swarm":
            # swarm can crash on many points or identical x-values; catch and fallback
            try:
                sns.swarmplot(                    data=plot_data,
                    x=config.condition_col,
                    y=config.measurement,
                    hue=config.hue_col,
                    order=order,
                    hue_order=hue_order,
                    dodge=config.hue_col is not None,
                    size=config.point_size,
                    ax=ax,
                )
            except Exception as exc:
                warnings.append(f"swarmplot failed ({exc}); falling back to stripplot.")
                sns.stripplot(
                    data=plot_data,
                    x=config.condition_col,
                    y=config.measurement,
                    hue=config.hue_col,
                    order=order,
                    hue_order=hue_order,
                    dodge=config.hue_col is not None,
                    jitter=config.jitter,
                    alpha=config.point_alpha,
                    size=config.point_size,
                    ax=ax,
                )

        else:
            raise ValueError(
                f"Unknown plot_type {config.plot_type!r}. "
                "Expected one of: 'violin_box', 'box', 'box_strip', "
                "'strip', or 'swarm'."
            )
    except Exception as exc:
        # ensure GUI gets the figure and a warning rather than a crash
        warnings.append(f"Plotting failed: {exc}")
        # add a minimal informative text on the axes
        ax.clear()
        ax.text(
            0.5, 0.5,
            "Plotting failed; see warnings for details.",
            ha="center", va="center",
        )

    if config.show_n:
        _add_n_to_xtick_labels(
            ax,
            counts,
            condition_col=config.condition_col,
            order=order,
            condition_labels=config.condition_labels,
            n_label=config.n_label,
        )

    _finish_axes(ax, config)

    return MorphologyPlotResult(
        fig=fig,
        ax=ax,
        data=plot_data,
        counts=counts,
        warnings=warnings,
    )

def discover_plottable_columns(df: pd.DataFrame) -> dict[str, list[str]]:
    """
    Return columns the GUI can present:
      - 'numeric': numeric-like columns (for measurement dropdown)
      - 'morphology': default morphology columns present and numeric
      - 'metadata': available metadata columns useful for grouping/hue
    """
    numeric = get_numeric_columns(df, exclude_metadata=True)
    morphology = get_morphology_columns(df)
    metadata = [c for c in df.columns if c not in numeric and c not in morphology]
    return {"numeric": numeric, "morphology": morphology, "metadata": metadata}

def save_figure(
    fig: Figure,
    path: str | Path,
    *,
    dpi: int = 300,
    transparent: bool = False,
) -> Path:
    """
    Save a matplotlib figure to disk.

    This is separated into its own function so the napari GUI can expose a
    simple "Save plot" button.
    """

    path = Path(path).expanduser()
    path.parent.mkdir(parents=True, exist_ok=True)

    fig.savefig(
        path,
        dpi=dpi,
        bbox_inches="tight",
        transparent=transparent,
    )

    return path